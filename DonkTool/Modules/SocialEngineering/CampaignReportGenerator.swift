    static func generateJSONReport(for campaign: PhishingCampaign) -> Data? {
        let report: [String: Any] = [
            "campaign": [
                "id": campaign.id.uuidString,
                "name": campaign.name,
                "description": campaign.description,
                "organization": campaign.targetOrganization,
                "status": campaign.status.rawValue,
                "created_at": ISO8601DateFormatter().string(from: campaign.createdAt),
                "launched_at": campaign.launchedAt.map { ISO8601DateFormatter().string(from: $0) } ?? nil,
                "completed_at": campaign.completedAt.map { ISO8601DateFormatter().string(from: $0) } ?? nil
            ],
            "template": [
                "name": campaign.emailTemplate.name,
                "category": campaign.emailTemplate.category.rawValue,
                "difficulty": campaign.emailTemplate.difficulty.rawValue,
                "subject": campaign.emailTemplate.subject
            ],
            "metrics": [
                "total_targets": campaign.targets.count,
                "emails_sent": campaign.metrics.emailsSent,
                "emails_opened": campaign.metrics.emailsOpened,
                "links_clicked": campaign.metrics.linksClicked,
                "credentials_submitted": campaign.metrics.credentialsSubmitted,
                "reported_as_phishing": campaign.metrics.reportsReceived,
                "open_rate": campaign.metrics.openRate,
                "click_rate": campaign.metrics.clickRate,
                "submission_rate": campaign.metrics.submissionRate,
                "report_rate": campaign.metrics.reportRate
            ],
            "risk_assessment": [
                "level": calculateRiskLevel(campaign.metrics),
                "score": calculateRiskScore(campaign.metrics),
                "description": getRiskDescription(campaign.metrics)
            ],
            "department_breakdown": generateDepartmentJSON(campaign),
            "generated_at": ISO8601DateFormatter().string(from: Date()),
            "generated_by": "DonkTool Social Engineering Module"
        ]
        
        return try? JSONSerialization.data(withJSONObject: report, options: .prettyPrinted)
    }
    
    // MARK: - Helper Functions
    
    private static func formatDate(_ date: Date?) -> String {
        guard let date = date else { return "N/A" }
        let formatter = DateFormatter()
        formatter.dateStyle = .medium
        formatter.timeStyle = .short
        return formatter.string(from: date)
    }
    
    private static func formatDateRange(_ campaign: PhishingCampaign) -> String {
        let start = formatDate(campaign.launchedAt)
        let end = formatDate(campaign.completedAt)
        return "\(start) - \(end)"
    }
    
    private static func calculateRiskLevel(_ metrics: CampaignMetrics) -> String {
        let riskScore = calculateRiskScore(metrics)
        
        switch riskScore {
        case ..<20: return "LOW"
        case 20..<40: return "MEDIUM"
        case 40..<60: return "HIGH"
        default: return "CRITICAL"
        }
    }
    
    private static func calculateRiskScore(_ metrics: CampaignMetrics) -> Double {
        return (metrics.clickRate * 0.4) + (metrics.submissionRate * 0.5) - (metrics.reportRate * 0.1)
    }
    
    private static func getRiskClass(_ metrics: CampaignMetrics) -> String {
        let level = calculateRiskLevel(metrics)
        switch level {
        case "LOW": return "risk-low"
        case "MEDIUM": return "risk-medium"
        default: return "risk-high"
        }
    }
    
    private static func getRiskDescription(_ metrics: CampaignMetrics) -> String {
        let level = calculateRiskLevel(metrics)
        switch level {
        case "LOW":
            return "Excellent security awareness. Employees demonstrated good ability to identify phishing attempts."
        case "MEDIUM":
            return "Moderate risk. Some employees fell for the phishing attempt. Additional training recommended."
        case "HIGH":
            return "High risk. Significant number of employees were susceptible to phishing. Immediate action required."
        default:
            return "Critical risk. Organization is highly vulnerable to phishing attacks. Comprehensive security training and controls needed immediately."
        }
    }
    
    private static func calculateBounceRate(_ campaign: PhishingCampaign) -> Double {
        let bounced = campaign.targets.filter { $0.status == .bounced }.count
        guard campaign.targets.count > 0 else { return 0 }
        return Double(bounced) / Double(campaign.targets.count) * 100
    }
    
    private static func formatAverageTimeToClick(_ campaign: PhishingCampaign) -> String {
        let clickedTargets = campaign.targets.filter { 
            $0.emailSentAt != nil && $0.linkClickedAt != nil 
        }
        
        guard !clickedTargets.isEmpty else { return "N/A" }
        
        let totalTime = clickedTargets.compactMap { target -> TimeInterval? in
            guard let sent = target.emailSentAt, let clicked = target.linkClickedAt else { return nil }
            return clicked.timeIntervalSince(sent)
        }.reduce(0, +)
        
        let averageTime = totalTime / Double(clickedTargets.count)
        
        let hours = Int(averageTime) / 3600
        let minutes = (Int(averageTime) % 3600) / 60
        
        if hours > 0 {
            return "\(hours)h \(minutes)m"
        } else if minutes > 0 {
            return "\(minutes) minutes"
        } else {
            return "< 1 minute"
        }
    }
    
    private static func generateRecommendations(for campaign: PhishingCampaign) -> String {
        var recommendations: [String] = []
        
        let riskLevel = calculateRiskLevel(campaign.metrics)
        
        // Add risk-level specific recommendations
        switch riskLevel {
        case "CRITICAL":
            recommendations.append("⚠️ **CRITICAL RISK**: Immediate executive briefing and comprehensive security intervention required")
        case "HIGH":
            recommendations.append("🔴 **HIGH RISK**: Organization-wide security training must be implemented within 30 days")
        default:
            break
        }
        
        if campaign.metrics.clickRate > 30 {
            recommendations.append("1. **Immediate Action Required**: Conduct targeted security awareness training for all employees")
            recommendations.append("2. **Email Security**: Implement additional email security controls and filtering")
        }
        
        if campaign.metrics.submissionRate > 10 {
            recommendations.append("3. **Credential Security**: Enforce multi-factor authentication (MFA) for all accounts")
            recommendations.append("4. **Incident Response**: Review and update incident response procedures")
        }
        
        if campaign.metrics.reportRate < 20 {
            recommendations.append("5. **Reporting Culture**: Improve phishing reporting processes and employee confidence")
        }
        
        recommendations.append("6. **Follow-up**: Schedule follow-up campaigns to measure improvement")
        recommendations.append("7. **Recognition**: Reward employees who correctly identified and reported the phishing attempt")
        
        return recommendations.joined(separator: "\n")
    }
    
    private static func generateDepartmentBreakdown(_ campaign: PhishingCampaign) -> String {
        let departments = Dictionary(grouping: campaign.targets, by: { $0.department ?? "Unknown" })
        
        var breakdown = ""
        for (dept, targets) in departments.sorted(by: { $0.key < $1.key }) {
            let clicked = targets.filter { $0.linkClickedAt != nil }.count
            let submitted = targets.filter { $0.credentialsSubmittedAt != nil }.count
            let reported = targets.filter { $0.reportedAsPhishingAt != nil }.count
            
            breakdown += """
            
            **\(dept)**
            - Targets: \(targets.count)
            - Clicked: \(clicked) (\(String(format: "%.1f%%", Double(clicked) / Double(targets.count) * 100)))
            - Submitted: \(submitted) (\(String(format: "%.1f%%", Double(submitted) / Double(targets.count) * 100)))
            - Reported: \(reported) (\(String(format: "%.1f%%", Double(reported) / Double(targets.count) * 100)))
            
            """
        }
        
        return breakdown
    }
    
    private static func generateTimelineAnalysis(_ campaign: PhishingCampaign) -> String {
        guard let launchedAt = campaign.launchedAt else {
            return "Campaign timeline data not available."
        }
        
        let timeline = """
        **Campaign Launch**: \(formatDate(launchedAt))
        **First Email Open**: \(formatDate(getFirstInteractionDate(campaign.targets, type: "open")))
        **First Link Click**: \(formatDate(getFirstInteractionDate(campaign.targets, type: "click")))
        **First Credential Submission**: \(formatDate(getFirstInteractionDate(campaign.targets, type: "submit")))
        **Campaign Completion**: \(formatDate(campaign.completedAt))
        """
        
        return timeline
    }
    
    private static func getFirstInteractionDate(_ targets: [PhishingTarget], type: String) -> Date? {
        switch type {
        case "open":
            return targets.compactMap { $0.emailOpenedAt }.min()
        case "click":
            return targets.compactMap { $0.linkClickedAt }.min()
        case "submit":
            return targets.compactMap { $0.credentialsSubmittedAt }.min()
        default:
            return nil
        }
    }
    
    private static func generateHTMLDepartmentTable(_ campaign: PhishingCampaign) -> String {
        let departments = Dictionary(grouping: campaign.targets, by: { $0.department ?? "Unknown" })
        
        var tableHTML = """
        <table class="department-table">
            <thead>
                <tr>
                    <th>Department</th>
                    <th>Targets</th>
                    <th>Clicked</th>
                    <th>Submitted</th>
                    <th>Reported</th>
                    <th>Risk Level</th>
                </tr>
            </thead>
            <tbody>
        """
        
        for (dept, targets) in departments.sorted(by: { $0.key < $1.key }) {
            let clicked = targets.filter { $0.linkClickedAt != nil }.count
            let submitted = targets.filter { $0.credentialsSubmittedAt != nil }.count
            let reported = targets.filter { $0.reportedAsPhishingAt != nil }.count
            
            let riskPercentage = Double(clicked) / Double(targets.count) * 100
            let riskClass = riskPercentage > 40 ? "risk-high" : (riskPercentage > 20 ? "risk-medium" : "risk-low")
            let riskLabel = riskPercentage > 40 ? "HIGH" : (riskPercentage > 20 ? "MEDIUM" : "LOW")
            
            tableHTML += """
                <tr>
                    <td><strong>\(dept)</strong></td>
                    <td>\(targets.count)</td>
                    <td>\(clicked) (\(String(format: "%.1f%%", Double(clicked) / Double(targets.count) * 100)))</td>
                    <td>\(submitted) (\(String(format: "%.1f%%", Double(submitted) / Double(targets.count) * 100)))</td>
                    <td>\(reported) (\(String(format: "%.1f%%", Double(reported) / Double(targets.count) * 100)))</td>
                    <td><span class="\(riskClass)">\(riskLabel)</span></td>
                </tr>
            """
        }
        
        tableHTML += """
            </tbody>
        </table>
        """
        
        return tableHTML
    }
    
    private static func generateHTMLRecommendations(_ campaign: PhishingCampaign) -> String {
        let recommendations = generateRecommendations(for: campaign)
        let htmlRecommendations = recommendations
            .components(separatedBy: "\n")
            .map { line in
                if line.hasPrefix("**") && line.hasSuffix("**") {
                    return "<div class='recommendation'>\(line.replacingOccurrences(of: "**", with: ""))</div>"
                } else {
                    return "<p>\(line)</p>"
                }
            }
            .joined()
        
        return htmlRecommendations
    }
    
    private static func generateDepartmentJSON(_ campaign: PhishingCampaign) -> [[String: Any]] {
        let departments = Dictionary(grouping: campaign.targets, by: { $0.department ?? "Unknown" })
        
        return departments.map { dept, targets in
            let clicked = targets.filter { $0.linkClickedAt != nil }.count
            let submitted = targets.filter { $0.credentialsSubmittedAt != nil }.count
            let reported = targets.filter { $0.reportedAsPhishingAt != nil }.count
            
            return [
                "department": dept,
                "total_targets": targets.count,
                "clicked": clicked,
                "submitted": submitted,
                "reported": reported,
                "click_rate": targets.count > 0 ? Double(clicked) / Double(targets.count) * 100 : 0,
                "submission_rate": targets.count > 0 ? Double(submitted) / Double(targets.count) * 100 : 0,
                "report_rate": targets.count > 0 ? Double(reported) / Double(targets.count) * 100 : 0
            ]
        }
    }
